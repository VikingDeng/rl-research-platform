type I18nContextValue = {
  locale: AppLocale;
  setLocale: (locale: AppLocale) => void;
  t: (key: string, fallback?: string) => string;
  tx: (zh: string, en: string) => string;
  isZh: boolean;
};

const detectInitialLocale = (): AppLocale => {
  if (typeof window === 'undefined') return 'zh-CN';
  const saved = window.localStorage.getItem(LOCALE_STORAGE_KEY);
  if (saved === 'zh-CN' || saved === 'en-US') return saved;
  const browserLang = window.navigator.language.toLowerCase();
  if (browserLang.startsWith('zh')) return 'zh-CN';
  return 'en-US';
};

const I18nContext = createContext<I18nContextValue>({
  locale: 'zh-CN',
  setLocale: () => undefined,
  t: (key: string, fallback?: string) => fallback || key,
  tx: (zh: string, en: string) => zh || en,
  isZh: true,
});

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [locale, setLocale] = useState<AppLocale>(detectInitialLocale);

  useEffect(() => {
    if (typeof window === 'undefined') return;
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
    document.documentElement.lang = locale;
    document.body.dataset.locale = locale;
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => {
    const t = (key: string, fallback?: string): string => {
      const localized = messages[locale]?.[key];
      if (typeof localized === 'string' && localized.length > 0) return localized;
      const english = messages['en-US']?.[key];
      if (typeof english === 'string' && english.length > 0) return english;
      return fallback || key;
    };

    return {
      locale,
      setLocale,
      t,
      tx: (zh: string, en: string) => (locale === 'zh-CN' ? zh : en),
      isZh: locale === 'zh-CN',
    };
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = () => useContext(I18nContext);
